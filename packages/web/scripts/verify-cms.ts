import { call } from "@orpc/server";
import { eq, sql } from "drizzle-orm";
import { DeleteObjectCommand } from "@aws-sdk/client-s3";
import { writeFile } from "node:fs/promises";
import assert from "node:assert/strict";
import { auth } from "../src/api/auth";
import { db } from "../src/api/database";
import { listings as table, advisors as directory } from "../src/api/database/schema";
import { listings } from "../src/api/routes/listings";
import { advisors } from "../src/api/routes/advisors";
import { upload } from "../src/api/routes/upload";
import { s3, getObjectBytes } from "../src/api/lib/s3";

// Isolated service verification only: no real account/session is created.
const original = auth.api.getSession;
Object.assign(auth.api, { getSession: async () => ({ user: { id: "cms-verification" } }) });
const options = { context: { headers: new Headers() } };
let id: number | undefined; let advisorId: number | undefined; const pdfRefs: string[] = [];
const before = await db.all(sql`select id, ref, publication from listings order by id`);
const ref = `VERIFY-${crypto.randomUUID().slice(0, 8)}`;
try {
  const imageUpload = await call(upload.presignListing, { filename: `verification-${crypto.randomUUID()}.jpg`, contentType: "image/jpeg" }, options);
  pdfRefs.push(imageUpload.ref);
  const put = await fetch(imageUpload.url, { method: "PUT", body: await Bun.file("public/images/house-1.jpg").arrayBuffer(), headers: { "Content-Type": "image/jpeg" } });
  assert.ok(put.ok, "Presigned image PUT must succeed");
  assert.ok((await getObjectBytes(imageUpload.ref.slice(3))).bytes.length > 1000);
  console.log("PASS authenticated presign + live storage image PUT/GET roundtrip.");
  const a = await call(advisors.save, { data: { name: "Verification Advisor", title: "Property Advisor", image: "/images/founder.jpg", active: true } }, options); advisorId = a.id;
  const data = { ref, type: "house" as const, deal: "stay" as const, title: "Integration verification only — not a real property", summary: "Test fixture, removed after verification.", description: "This is an automated verification of the publishing workflow, not an available property.", price: 9876543, priceDisplay: "on-request" as const, district: "Verification district", province: "Chiang Rai", areaSqm: 180, landSqm: 1600, bedrooms: 3, bathrooms: 2, views: "Test garden", furnishing: "Furnished", advisorIds: [a.id], images: ["/images/house-1.jpg", "/images/house-2.jpg"], floorPlanImage: "/images/plan-house.jpg", latitude: 19.91, longitude: 99.83 };
  data.images[0] = imageUpload.ref;
  let row = await call(listings.create, data, options); id = row.id;
  assert.equal(row.publication, "draft");
  assert.equal((await call(listings.list, { q: ref }, options)).length, 0);
  assert.equal((await call(listings.adminList, { q: ref }, options)).length, 1);
  await assert.rejects(call(listings.create, data, options), /Reference already exists/);
  const preview = await call(listings.get, { id }, options); assert.equal(preview.listing.price, null); assert.equal(preview.listing.advisorProfiles[0]?.name, "Verification Advisor");
  row = await call(listings.publish, { id, revision: row.revision }, options); pdfRefs.push(row.brochureRef!);
  assert.equal(row.publication, "published");
  const results = await call(listings.list, { q: ref, deal: "stay", type: "house" }, options); assert.equal(results.length, 1); assert.equal(results[0]?.price, null); assert.ok(results[0]?.brochureUrl);
  assert.equal((await call(listings.list, { q: ref, deal: "rent" }, options)).length, 0);
  assert.equal((await call(listings.list, { q: ref, minPrice: 1 }, options)).length, 0);
  assert.ok((await call(listings.meta, undefined, options)).districts.includes("Verification district"));
  const pdf1 = await getObjectBytes(row.brochureRef!.slice(3)); await writeFile("/home/user/cms-on-request-verification.pdf", pdf1.bytes);
  console.log("PASS persisted draft/create/directory, publish to storage, Stay-only filters, metadata, private-price API redaction, brochure download.");
  await assert.rejects(call(listings.update, { id, revision: 999, data }, options), /changed in another tab/);
  const numeric = { ...data, priceDisplay: "starting-from" as const, negotiable: true };
  row = await call(listings.update, { id, revision: row.revision, data: numeric }, options); assert.equal(row.publication, "draft"); assert.equal(row.brochureRef, null);
  assert.equal((await call(listings.list, { q: ref }, options)).length, 0);
  row = await call(listings.publish, { id, revision: row.revision }, options); pdfRefs.push(row.brochureRef!);
  const pdf2 = await getObjectBytes(row.brochureRef!.slice(3)); await writeFile("/home/user/cms-numeric-verification.pdf", pdf2.bytes);
  row = await call(listings.unpublish, { id, revision: row.revision }, options); assert.equal(row.publication, "draft");
  row = await call(listings.update, { id, revision: row.revision, data: { ...data, images: ["/images/does-not-exist.jpg"] } }, options);
  await assert.rejects(call(listings.publish, { id, revision: row.revision }, options), /Publication failed/);
  assert.equal((await call(listings.raw, { id }, options)).publication, "draft");
  row = await call(listings.update, { id, revision: row.revision, data: { ...data, description: Array(130).fill("Paragraph.").join("\n\n") } }, options);
  await assert.rejects(call(listings.publish, { id, revision: row.revision }, options), /four-page layout/);
  assert.equal((await call(listings.raw, { id }, options)).publication, "draft");
  assert.equal((await call(listings.meta, undefined, options)).districts.includes("Verification district"), false);
  await assert.rejects(call(listings.create, { ...data, ref: `${ref}-invalid`, longitude: null }, options));
  console.log("PASS revision conflict, save withdraws publication, new revision PDF, explicit withdraw and failed-media rollback.");
  Object.assign(auth.api, { getSession: async () => null });
  await assert.rejects(call(listings.get, { id }, options)); await assert.rejects(call(listings.raw, { id }, options)); await assert.rejects(call(advisors.list, undefined, options));
  console.log("PASS unauthenticated draft/admin/directory protection.");
} finally {
  Object.assign(auth.api, { getSession: original });
  if (id) await db.delete(table).where(eq(table.id, id));
  if (advisorId) await db.delete(directory).where(eq(directory.id, advisorId));
  for (const ref of pdfRefs) await s3.send(new DeleteObjectCommand({ Bucket: process.env.S3_BUCKET, Key: ref.slice(3) }));
  assert.deepEqual(await db.all(sql`select id, ref, publication from listings order by id`), before);
  console.log("Verification records/PDF objects removed; pre-existing listing rows unchanged.");
}